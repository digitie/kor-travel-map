async def test_0200_rejects_unsafe_preprovisioned_role_before_schema_ddl(
    gate_alembic_config: Config,
) -> None:
    """bootstrap role 속성이 unsafe면 baseline table을 만들기 전에 거부한다."""

    from tests.integration._tvn34_migration_bootstrap import (
        alembic_schema_owner_role,
        bootstrapped_migrator_dsn,
    )

    cfg = gate_alembic_config
    admin_dsn = cfg.get_main_option("sqlalchemy.url")
    assert admin_dsn is not None
    cfg.set_main_option("sqlalchemy.url", await bootstrapped_migrator_dsn(admin_dsn))
    await _admin_execute(
        admin_dsn,
        "ALTER ROLE ktm_curation_command_owner REPLICATION",
    )
    try:
        with alembic_schema_owner_role(), pytest.raises(
            DBAPIError,
            match="application NOLOGIN role is missing or unsafe",
        ):
            await asyncio.to_thread(command.upgrade, cfg, "0200_schema_baseline")
        assert await _admin_fetchval(
            admin_dsn,
            "SELECT to_regclass('feature.features') IS NULL",
        ) is True
    finally:
        await _admin_execute(
            admin_dsn,
            "ALTER ROLE ktm_curation_command_owner NOREPLICATION",
        )


async def test_0202_rejects_membership_option_and_extra_edge_drift(
    gate_alembic_config: Config,
) -> None:
    """0202는 expected edge option 변화와 교차 executor edge를 모두 거부한다."""

    from tests.integration._tvn34_migration_bootstrap import (
        alembic_schema_owner_role,
        bootstrapped_migrator_dsn,
    )

    cfg = gate_alembic_config
    admin_dsn = cfg.get_main_option("sqlalchemy.url")
    assert admin_dsn is not None
    cfg.set_main_option("sqlalchemy.url", await bootstrapped_migrator_dsn(admin_dsn))
    with alembic_schema_owner_role():
        await asyncio.to_thread(command.upgrade, cfg, "0200_schema_baseline")

    mutations = (
        (
            "GRANT ktm_curation_admin_executor TO ktm_feature_api_runtime "
            "WITH ADMIN TRUE, INHERIT TRUE, SET FALSE",
            "GRANT ktm_curation_admin_executor TO ktm_feature_api_runtime "
            "WITH ADMIN FALSE, INHERIT TRUE, SET FALSE",
        ),
        (
            "GRANT ktm_curation_provider_executor TO ktm_feature_api_runtime "
            "WITH ADMIN FALSE, INHERIT TRUE, SET FALSE",
            "REVOKE ktm_curation_provider_executor FROM ktm_feature_api_runtime",
        ),
    )
    for mutation, restore in mutations:
        await _admin_execute(admin_dsn, mutation)
        try:
            with alembic_schema_owner_role(), pytest.raises(
                DBAPIError,
                match="application role membership graph is not exact",
            ):
                await asyncio.to_thread(command.upgrade, cfg, "0202_tvn40_curation_receipts")
            assert await _admin_fetchval(
                admin_dsn,
                "SELECT version_num FROM public.alembic_version",
            ) == "0200_schema_baseline"
        finally:
            await _admin_execute(admin_dsn, restore)
