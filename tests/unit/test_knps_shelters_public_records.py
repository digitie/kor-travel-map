"""대피소 SHP의 public provider → Map 계약 회귀 (#1450, knps-api#17).

HTTP bytes만 대체한다. typed record와 Map 변환기는 실제 public 구현을 쓴다.
합성 archive(ID_CD/KOR_NM·CP949·EPSG:5179/4326)는 중첩·Polygon 제외·identity 계약을,
``fixtures/knps_shelters_20230928_FILE_000000003681543.zip``은 data.go.kr 2982556의 현재
공식 배포본(2026-11-09 수신, 평면 SHP 22 Point, UTF-8, EPSG:5186, 잘린 순한글 DBF
필드명)을 그대로 고정한다.
"""

from __future__ import annotations

import io
import zipfile
from datetime import datetime
from pathlib import Path
from typing import Any
from zoneinfo import ZoneInfo

import httpx
import pytest
import shapefile
from knps import KnpsClient
from pyproj import CRS, Transformer

from kortravelmap.core.ids import make_feature_id, make_payload_hash, make_source_record_key
from kortravelmap.dto import Address, FeatureBundle, FeatureKind, SourceRole
from kortravelmap.providers.knps import knps_point_records_to_bundles

SHELTER_DATASET = "knps_shelters"
FETCHED_AT = datetime(2026, 11, 7, 9, 0, tzinfo=ZoneInfo("Asia/Seoul"))
FIXTURE_BJD = "4211000000"
SHELTER_POINTS = (
    ("SHELTER-A", "합성 북쪽 대피소", 128.535422, 37.130878, "원문 보존 · 북쪽"),
    ("SHELTER-B", "합성 남쪽 대피소", 128.843683, 36.727438, "원문 보존 · 남쪽"),
)


def _shape_zip(index: int, *, crs: str, polygon: bool = False) -> bytes:
    """동일한 로컬 OBJECTID를 가진 별도 SHP에서도 전역 ID_CD를 보존한다."""
    source_id, name, lon, lat, note = SHELTER_POINTS[index]
    projected = Transformer.from_crs("EPSG:4326", crs, always_xy=True)
    x, y = projected.transform(lon, lat)
    shp, shx, dbf = io.BytesIO(), io.BytesIO(), io.BytesIO()
    with shapefile.Writer(
        shp=shp,
        shx=shx,
        dbf=dbf,
        shapeType=shapefile.POLYGON if polygon else shapefile.POINT,
        encoding="cp949",
    ) as writer:
        writer.field("ID_CD", "C", size=40)
        writer.field("OBJECTID", "C", size=12)
        writer.field("KOR_NM", "C", size=100)
        writer.field("NOTE", "C", size=100)
        if polygon:
            delta = 10 if crs != "EPSG:4326" else 0.001
            writer.poly(
                [
                    [
                        (x - delta, y - delta),
                        (x - delta, y + delta),
                        (x + delta, y + delta),
                        (x + delta, y - delta),
                        (x - delta, y - delta),
                    ]
                ]
            )
            # Same facility key, different geometry: must not become another place.
            writer.record(source_id, "1", "제외할 대피소 부지 면", "POLYGON_ONLY")
        else:
            writer.point(x, y)
            writer.record(source_id, "1", name, note)
    archive = io.BytesIO()
    with zipfile.ZipFile(archive, "w", compression=zipfile.ZIP_DEFLATED) as output:
        for suffix, content in (
            (".shp", shp.getvalue()),
            (".shx", shx.getvalue()),
            (".dbf", dbf.getvalue()),
            (".prj", CRS.from_user_input(crs).to_wkt().encode("utf-8")),
            (".cpg", b"CP949"),
        ):
            output.writestr("layers/SHELTER" + suffix, content)
    return archive.getvalue()


def build_shelter_archive(*, crs: str = "EPSG:5179", reverse_members: bool = False) -> bytes:
    """Parent live harness용: PT 두 행 + 같은 ID의 PG 면을 담은 합성 중첩 ZIP."""
    members = [
        ("GSTN_SHELTER_PT2.zip", _shape_zip(0, crs=crs)),
        ("GSTN_SHELTER_PT3.zip", _shape_zip(1, crs=crs)),
        ("GSTN_SHELTER_PG.ZIP", _shape_zip(0, crs=crs, polygon=True)),
    ]
    if reverse_members:
        members.reverse()
    archive = io.BytesIO()
    with zipfile.ZipFile(archive, "w", compression=zipfile.ZIP_DEFLATED) as output:
        for filename, payload in members:
            output.writestr("nested/" + filename, payload)
    return archive.getvalue()


async def _public_records(payload: bytes) -> tuple[Any, ...]:
    requested: list[str] = []

    async def respond(request: httpx.Request) -> httpx.Response:
        assert request.method == "GET"
        assert request.url == httpx.URL(download_url)
        requested.append(str(request.url))
        return httpx.Response(200, content=payload, headers={"Content-Type": "application/zip"})

    async with (
        httpx.AsyncClient(transport=httpx.MockTransport(respond)) as session,
        KnpsClient(session=session, max_rps=1000) as client,
    ):
        dataset = next(item for item in client.file_datasets() if item.key == SHELTER_DATASET)
        assert dataset.download_url
        download_url = dataset.download_url
        records = await client.files.read_place_records(SHELTER_DATASET)
    assert requested == [download_url]
    return records


async def fixture_address(_coord: object) -> Address:
    """명시적인 합성 reverse 결과; 실제 행정경계 검증 결과로 주장하지 않는다."""
    return Address(bjd_code=FIXTURE_BJD)


def _semantic_bundle(bundle: FeatureBundle) -> dict[str, Any]:
    # Exclude only audit timestamps generated by DTO default_factory=kst_now.
    # Keep fetched_at, expires_at, raw (including any embedded dates), identity,
    # hashes, source keys, coordinates, categories, state/version and provenance.
    return bundle.model_dump(
        mode="json",
        exclude={
            "feature": {"created_at", "updated_at"},
            "source_record": {"imported_at"},
            "source_link": {"created_at"},
        },
    )


@pytest.mark.parametrize("crs", ["EPSG:5179", "EPSG:4326"])
@pytest.mark.asyncio
async def test_public_nested_shelter_records_preserve_map_contract(crs: str) -> None:
    records = await _public_records(build_shelter_archive(crs=crs))
    assert len(records) == 2  # PG polygon must not be counted as a third shelter.
    by_id = {record.source_id: record for record in records}
    assert len(by_id) == 2
    assert set(by_id) == {point[0] for point in SHELTER_POINTS}
    bundles = await knps_point_records_to_bundles(
        records,
        dataset_key=SHELTER_DATASET,
        fetched_at=FETCHED_AT,
        reverse_geocoder=fixture_address,
    )
    assert len(bundles) == 2
    bundles_by_id = {bundle.source_record.source_entity_id: bundle for bundle in bundles}
    for source_id, name, lon, lat, note in SHELTER_POINTS:
        record, bundle = by_id[source_id], bundles_by_id[source_id]
        assert record.dataset_key == SHELTER_DATASET
        assert record.name == name
        assert record.longitude == pytest.approx(lon, abs=1e-7)
        assert record.latitude == pytest.approx(lat, abs=1e-7)
        assert record.raw["ID_CD"] == source_id
        assert record.raw["OBJECTID"] == "1"
        assert record.raw["KOR_NM"] == name
        assert record.raw["NOTE"] == note
        feature, source, link = bundle.feature, bundle.source_record, bundle.source_link
        assert feature.provider_natural_key == source_id
        assert feature.kind is FeatureKind.PLACE
        assert feature.name == name
        assert feature.category == "03080100"
        assert feature.marker_icon == "shelter"
        assert feature.marker_color == "P-06"
        assert feature.detail.place_kind == "mountain_shelter"
        assert feature.detail.payload == {"knps_dataset": SHELTER_DATASET}
        assert feature.coord is not None
        assert float(feature.coord.lon) == pytest.approx(lon, abs=1e-7)
        assert float(feature.coord.lat) == pytest.approx(lat, abs=1e-7)
        assert feature.address.bjd_code == FIXTURE_BJD
        assert feature.feature_id == make_feature_id(
            bjd_code=FIXTURE_BJD,
            kind="place",
            category="03080100",
            source_type="python-knps-api:" + SHELTER_DATASET,
            source_natural_key=source_id,
        )
        assert source.provider == "python-knps-api"
        assert source.dataset_key == SHELTER_DATASET
        assert source.source_entity_type == "knps_facility"
        assert source.source_entity_id == source_id
        assert source.raw_data == record.raw
        assert source.raw_payload_hash == make_payload_hash(record.raw)
        assert source.source_record_key == make_source_record_key(
            provider="python-knps-api",
            dataset_key=SHELTER_DATASET,
            source_entity_type="knps_facility",
            source_entity_id=source_id,
            raw_payload_hash=source.raw_payload_hash,
        )
        assert source.fetched_at == FETCHED_AT
        assert link.source_role is SourceRole.PRIMARY
        assert link.match_method == "natural_key"
        assert link.confidence == 100
        assert link.feature_id == feature.feature_id
        assert link.source_record_key == source.source_record_key


@pytest.mark.asyncio
async def test_public_nested_shelter_replay_keeps_identity_and_raw() -> None:
    payload = build_shelter_archive()
    first = await _public_records(payload)
    again = await _public_records(payload)
    reordered = await _public_records(build_shelter_archive(reverse_members=True))

    async def project(records: tuple[Any, ...]) -> dict[str, Any]:
        bundles = await knps_point_records_to_bundles(
            records,
            dataset_key=SHELTER_DATASET,
            fetched_at=FETCHED_AT,
            reverse_geocoder=fixture_address,
        )
        return {
            bundle.source_record.source_entity_id: _semantic_bundle(bundle) for bundle in bundles
        }

    assert len(first) == len(again) == len(reordered) == 2
    assert await project(first) == await project(again) == await project(reordered)


@pytest.mark.asyncio
async def test_public_shelter_geometry_only_update_keeps_identity_but_versions_source(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    original_points = SHELTER_POINTS
    original_archive = build_shelter_archive()
    source_id, name, lon, lat, note = original_points[0]
    shifted_points = (
        (source_id, name, lon + 0.001, lat, note),
        *original_points[1:],
    )
    with monkeypatch.context() as patch:
        patch.setitem(globals(), "SHELTER_POINTS", shifted_points)
        moved_archive = build_shelter_archive()
    assert SHELTER_POINTS is original_points

    async def convert(payload: bytes) -> dict[str, Any]:
        records = await _public_records(payload)
        bundles = await knps_point_records_to_bundles(
            records,
            dataset_key=SHELTER_DATASET,
            fetched_at=FETCHED_AT,
            reverse_geocoder=fixture_address,
        )
        assert len(bundles) == 2
        return {bundle.source_record.source_entity_id: bundle for bundle in bundles}

    before = await convert(original_archive)
    after = await convert(moved_archive)
    assert before.keys() == after.keys()
    old, new = before[source_id], after[source_id]
    assert old.feature.name == new.feature.name == name
    assert old.feature.feature_id == new.feature.feature_id
    assert old.feature.provider_natural_key == new.feature.provider_natural_key == source_id
    assert old.feature.address.bjd_code == new.feature.address.bjd_code == FIXTURE_BJD
    assert old.feature.coord is not None
    assert new.feature.coord is not None
    assert float(old.feature.coord.lon) == pytest.approx(lon, abs=1e-7)
    assert float(new.feature.coord.lon) == pytest.approx(lon + 0.001, abs=1e-7)
    assert float(old.feature.coord.lat) == pytest.approx(lat, abs=1e-7)
    assert float(new.feature.coord.lat) == pytest.approx(lat, abs=1e-7)

    old_source, new_source = old.source_record, new.source_record
    assert old_source.source_entity_id == new_source.source_entity_id == source_id
    assert old_source.fetched_at == new_source.fetched_at == FETCHED_AT
    # Every DBF property is unchanged. A changed geometry string in raw must
    # version the Map source even though facility identity and name are stable.
    for key, value in {"ID_CD": source_id, "OBJECTID": "1", "KOR_NM": name, "NOTE": note}.items():
        assert old_source.raw_data[key] == new_source.raw_data[key] == value
    assert old_source.raw_data.keys() == new_source.raw_data.keys()
    changed_keys = {
        key for key in old_source.raw_data if old_source.raw_data[key] != new_source.raw_data[key]
    }
    assert changed_keys
    for key in changed_keys:
        assert isinstance(old_source.raw_data[key], str)
        assert isinstance(new_source.raw_data[key], str)
    assert old_source.raw_payload_hash == make_payload_hash(old_source.raw_data)
    assert new_source.raw_payload_hash == make_payload_hash(new_source.raw_data)
    assert old_source.raw_payload_hash != new_source.raw_payload_hash
    assert old_source.source_record_key != new_source.source_record_key
    assert old.source_link.source_record_key == old_source.source_record_key
    assert new.source_link.source_record_key == new_source.source_record_key

    # A second, stationary facility must not be versioned by ZIP-wide changes.
    unchanged_id = original_points[1][0]
    assert _semantic_bundle(before[unchanged_id]) == _semantic_bundle(after[unchanged_id])


OFFICIAL_ARCHIVE = Path(__file__).parent / "fixtures" / (
    "knps_shelters_20230928_FILE_000000003681543.zip"
)


@pytest.mark.asyncio
async def test_official_current_shelter_archive_becomes_22_map_places() -> None:
    records = await _public_records(OFFICIAL_ARCHIVE.read_bytes())
    assert len(records) == 22
    bundles = await knps_point_records_to_bundles(
        records,
        dataset_key=SHELTER_DATASET,
        fetched_at=FETCHED_AT,
        reverse_geocoder=fixture_address,
    )
    # 이름 없는 행 skip 없이 공식 22건이 모두 Map place가 된다.
    assert len(bundles) == 22
    assert len({bundle.feature.feature_id for bundle in bundles}) == 22
    # 현재 배포본에는 전역 ID가 없다: 순번을 멤버 범위로 hash한 source_id가 시설 identity다.
    source_ids = [bundle.source_record.source_entity_id for bundle in bundles]
    assert len(set(source_ids)) == 22
    assert all(source_id.startswith("shp:") for source_id in source_ids)
    replay = await _public_records(OFFICIAL_ARCHIVE.read_bytes())
    assert sorted(record.source_id for record in replay) == sorted(source_ids)
    by_name = {bundle.feature.name: bundle for bundle in bundles}
    assert {"중청대피소", "장터목대피소", "세석대피소", "희운각대피소"} <= set(by_name)
    # knps-api a472a37(#17 후속): 원천의 '現' 표식은 이름에서 걷히고 원문은 raw에 남는다.
    assert "노고단대피소" in by_name
    assert not any("現" in name or "舊" in name for name in by_name)
    nogodan_raw = by_name["노고단대피소"].source_record.raw_data
    assert nogodan_raw["시설물"] == "現노고단대피소"
    # 고친 이름은 해시에 들어가야 이미 現…로 적재된 운영 행이 다음 적재에서 고쳐진다.
    assert nogodan_raw["__map_display_name__"] == "노고단대피소"
    # 이름이 원천 값 그대로인 나머지 21건은 원천 행 그대로다(해시 불변 — 재변환 없음).
    plain = [bundle for bundle in bundles if bundle.feature.name != "노고단대피소"]
    assert len(plain) == 21
    assert all("__map_display_name__" not in b.source_record.raw_data for b in plain)
    for bundle in bundles:
        feature = bundle.feature
        assert feature.category == "03080100"
        assert feature.detail.place_kind == "mountain_shelter"
        assert feature.marker_icon == "shelter"
        assert feature.coord is not None
        assert 33.0 < float(feature.coord.lat) < 38.7
        assert 124.5 < float(feature.coord.lon) < 132.0
        assert bundle.source_record.raw_data["시설물_"] == "대피소"
    jungcheong = by_name["중청대피소"].feature
    assert jungcheong.coord is not None
    assert float(jungcheong.coord.lon) == pytest.approx(128.4604, abs=1e-6)
    assert float(jungcheong.coord.lat) == pytest.approx(38.120567, abs=1e-6)
