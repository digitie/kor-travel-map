@pytest.mark.asyncio
async def test_handoff_transaction_rolls_back_when_commit_time_postflight_fails(
    application_300_config: tuple[Config, str],
) -> None:
    """deferred trigger가 commit에서 실패해도 purge된 source row가 되살아야 한다."""

    config, admin_dsn = application_300_config
    await _prepare_logical_0236(config, admin_dsn)
    await _admin_execute(
        admin_dsn,
        """
        CREATE FUNCTION public.application_300_force_handoff_rollback()
        RETURNS trigger
        LANGUAGE plpgsql
        AS $$
        BEGIN
            RAISE EXCEPTION 'application-300 handoff commit probe';
        END
        $$;
        CREATE CONSTRAINT TRIGGER application_300_handoff_commit_probe
        AFTER INSERT ON public.alembic_version
        DEFERRABLE INITIALLY DEFERRED
        FOR EACH ROW
        EXECUTE FUNCTION public.application_300_force_handoff_rollback();
        """,
    )

    with pytest.raises(DBAPIError, match="application-300 handoff commit probe"):
        await _stamp(config)

    assert await _raw_version(admin_dsn) == (_HANDOFF_SOURCE,)
