async def test_existing_0104_bridge_upgrades_to_tvn40_head_without_baseline_replay(
    gate_alembic_config: Config,
) -> None:
    """기존 n150 `0104` revision은 baseline 재실행 없이 T-VN-40만 적용한다."""

