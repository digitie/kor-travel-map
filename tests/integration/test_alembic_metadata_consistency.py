@pytest.mark.asyncio
async def test_fresh_upgrade_rolls_back_when_public_text_search_residue_appears_after_bootstrap(
    pg_container: object,
) -> None:
    """bootstrap 뒤 끼어든 public semantic object는 `300` metadata를 남기지 않는다.

    official fresh image → role/extension bootstrap → migration 사이에는 normal runtime이
    개입하지 않아야 한다. 그래도 외부 superuser mutation을 repair하지 않고 final
    migration transaction 전체를 rollback해야 하므로, raw Alembic head와 application
    relation 모두 비어 있어야 한다.
    """

    from kortravelmap.infra.db import normalize_async_dsn

    raw_dsn = pg_container.get_connection_url()  # type: ignore[attr-defined]
    database = f"application_300_public_residue_{uuid4().hex}"
    await _admin_execute(raw_dsn, f'CREATE DATABASE "{database}"')
    admin_dsn = normalize_async_dsn(_with_database(raw_dsn, database))
    root = Path(__file__).resolve().parents[2]  # noqa: ASYNC240
    config = Config(str(root / "alembic.ini"))
    config.set_main_option("script_location", str(root / "alembic"))
    try:
        config.set_main_option(
            "sqlalchemy.url",
            await bootstrapped_application_300_migrator_dsn(admin_dsn),
        )
        await _admin_execute(
            admin_dsn,
            "CREATE TEXT SEARCH CONFIGURATION "
            "public.application_300_late_residue "
            "(PARSER = pg_catalog.default)",
        )

        with alembic_schema_owner_role(), pytest.raises(
            Exception, match="public residue catalog is not empty"
        ):
            await asyncio.to_thread(command.upgrade, config, "head")

        assert await _raw_version(admin_dsn) == ()
        connection = await _connect(admin_dsn)
        try:
            application_relation_count = await connection.fetchval(
                """
                SELECT count(*)
                FROM pg_catalog.pg_class AS object
                JOIN pg_catalog.pg_namespace AS namespace
                  ON namespace.oid = object.relnamespace
                WHERE namespace.nspname IN ('feature', 'provider_sync', 'ops')
                  AND object.relkind IN ('r', 'p', 'v', 'm', 'f', 'S')
                """
            )
        finally:
            await connection.close()
        assert application_relation_count == 0
    finally:
        await _admin_execute(raw_dsn, f'DROP DATABASE "{database}" WITH (FORCE)')


