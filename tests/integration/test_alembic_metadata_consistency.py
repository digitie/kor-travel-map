@pytest.mark.asyncio
async def test_head_schema_artifact_matches_head(
    application_300_config: tuple[Config, str],
) -> None:
    """커밋된 head 오라클이 실제 head와 같은지 잰다.

    `alembic/baseline/schema.sql`은 rev 300 시점 덤프라 301~ 이후를 담지 못한다.
    유도형 검사기 다섯이 그 파일에서 현행 계약을 유도하고 있었고, 그래서 head에만
    있는 제약·루틴을 **구조적으로 보지 못했다**. 오라클을 head로 옮기면 그 눈먼
    구간이 사라지지만, 오라클 자신이 낡으면 같은 결함이 이름만 바꿔 돌아온다.

    이 테스트가 그 재발을 막는다 — head가 바뀌면 여기서 빨개지고, 고치는 방법은
    아티팩트를 다시 뽑는 것뿐이다.

        KTM_WRITE_HEAD_SCHEMA=1 pytest -q -m integration \
            tests/integration/test_alembic_metadata_consistency.py \
    """

    _, admin_dsn = application_300_config
    assert await _raw_version(admin_dsn) == (_HEAD,)

    container = _CONTAINER_DATABASE["container"]
    database = _CONTAINER_DATABASE["database"]
    current = await asyncio.to_thread(dump_head_schema, container, database)

    if os.environ.get(REGENERATE_ENV) == "1":
        HEAD_SCHEMA_PATH.write_text(current, encoding="utf-8", newline="\n")
        pytest.skip(f"{REGENERATE_ENV}=1 — head 오라클을 다시 기록했다")

    if not HEAD_SCHEMA_PATH.is_file():
        pytest.fail(
            f"head 오라클이 없다: {HEAD_SCHEMA_PATH}. "
            f"{REGENERATE_ENV}=1 로 이 테스트를 한 번 돌려 만들어라."
        )
    committed = HEAD_SCHEMA_PATH.read_text(encoding="utf-8")
    if committed == current:
        return

    import difflib

    diff = "\n".join(
        list(
            difflib.unified_diff(
                committed.splitlines(),
                current.splitlines(),
                fromfile="committed head-schema.sql",
                tofile="live head",
                lineterm="",
            )
        )[:120]
    )
    pytest.fail(
        "head 오라클이 실제 head와 다르다 — 유도형 검사기가 낡은 세계를 보고 있다.\n"
        f"{REGENERATE_ENV}=1 로 다시 뽑아라.\n{diff}"
    )


@pytest.mark.asyncio
async def test_downgrade_is_rejected_without_mutation(
    application_300_config: tuple[Config, str],
) -> None:
    config, admin_dsn = application_300_config

    with alembic_schema_owner_role(), pytest.raises(
        RuntimeError,
        match="400_schema_baseline is forward-only",
    ):
        await asyncio.to_thread(
            # intentional-squash-boundary-rejection: all downgrade targets are forbidden.
            command.downgrade,
            config,
            "base",
        )

    assert await _raw_version(admin_dsn) == (_HEAD,)
